"""
docs.py — руководство и справочник внутри самого DARAVE.

## Почему документация живёт в коде, а не в отдельных файлах

Два правила, и оба из опыта этого проекта.

**Теория берётся из music_theory.py, а не переписывается.** Те же пять
блоков читает ассистент в системной подсказке. Если написать теорию
второй раз для человека, через месяц диджей и ассистент будут знать
РАЗНОЕ, причём молча: расхождение обнаружится только когда ассистент
посоветует то, чего в руководстве нет.

**Справочник приёмов собирается из TECHNIQUES.** Шестьдесят три приёма с
названиями, описаниями, шагами и ползунками — переписывать их в markdown
значит завести копию, которая устареет на первой же правке. Здесь
описания читаются из живого словаря, поэтому справочник не может
отстать от кода.

Своими словами написано только то, чего в коде нет: как этим
пользоваться и почему всё устроено именно так.
"""
from __future__ import annotations

GUIDE = """\
# Руководство

DARAVE собирает сет из вашей библиотеки: слушает треки, предлагает
переходы, даёт их отсудить и складывает одобренное в готовый набор.

Работа идёт по кругу из четырёх вкладок, и порядок в них не случайный.

## 1. Library — что у вас есть

Впишите папку с музыкой и нажмите **Анализ библиотеки**. Один проход
делает всё: разбирает треки, меряет темп и карты, считает слои,
определяет вокал, дописывает стили из каталогов, убирает мусор.

Считается **только то, чего не хватает**. Повторный запуск на
неизменившейся папке занимает доли секунды: у каждого файла запомнен
отпечаток (время правки и размер), и заново разбирается лишь новое и
переписанное.

Отбор в строке поиска понимает: `dnb 170-180 8A liquid vocal`. Точный
темп — это диапазон, а не равенство: анализатор отдаёт 173.97, и «174»
обязано его найти.

Удаление идёт тремя ступенями по весу: убрать из библиотеки (файл цел),
отправить в `_корзина` рядом, стереть насовсем.

## 2. Technician — из чего собирать

Справочник приёмов: что каждый делает, на каких стыках хорош, нужны ли
слои. Здесь же предпрослушка на ваших треках — не на демо-материале, а
на той паре, с которой вы работаете.

## 3. Clipping — главный экран

Система предлагает шов: пару треков, приём и две точки в секциях.
Вы слушаете и решаете.

Отказ спрашивает, **ЧТО именно** не так, и следующее предложение меняет
именно это:

* «не та техника» — пара остаётся, приём меняется;
* «другие секции» — пара и приём остаются, двигаются точки;
* «сменить трек B» — уходящий остаётся;
* «другая пара» — не подходит ничто.

Одобренное копится в пул справа. Пул — это материал сета, а не сам сет.

Кнопка **⟳ переслушать все** пересобирает демо всех отобранных швов по
текущей логике сведения. Нужна после правок в приёмах: сами швы не
меняются — меняется то, как они звучат.

Кнопка **✎ в отбор** у каждого шва возвращает его сюда на правку.
Одобрение заменяет прежнюю запись, а не заводит рядом вторую.

## 4. ControlC — сет целиком

Порядок, энергетическая дуга, хронометраж. Полоска под дугой показывает,
сколько играет каждый трек; жёлтым помечены те, что играют меньше двух
фраз (16 тактов) — столько трек играть не должен.

**По жёлтому можно кликнуть.** Откроется переход, который обрывает трек,
прямо в отборе; вас спросят, какой из двух чинить — тот, что уводит, или
тот, что заводит. Правка возвращается в план сама, пересобирать всё не
надо.

## Ассистент

Живёт в ControlC, потому что о плане спрашивают, глядя на план. Знает
теорию из этого же руководства, видит вашу библиотеку и умеет крутить
ручки: «убери низ на деке A», «поставь эхо на B».

## Порядок на каждый день

1. Library → **Анализ библиотеки** (подхватит новое).
2. Clipping → слушать и судить, пока пул не наберётся.
3. ControlC → **Собрать сет из пула**, посмотреть дугу и хронометраж.
4. Жёлтые стыки — починить кликом, вернуться к пункту 3.
"""

DJ_THEORY = """\
# Теория сведения

## Что вообще происходит в переходе

Переход — это не «сделать тише один и громче другой». Это четыре
независимые вещи, и каждая может испортить его в одиночку.

**Темп.** Треки должны идти в одном темпе, иначе доли разъезжаются.
DARAVE подгоняет темп скоростью, как винил, а не растяжением. У этого
есть цена: вместе с темпом уезжает высота. Сведение 174 к 153 — это
больше двух полутонов, то есть другая тональность, чего метки Камелота
уже не показывают. Отсюда предупреждение «±N центов» на карточке шва.

**Фразировка.** Музыка сложена из квадратов по 8, 16, 32 такта. Переход,
начатый не на границе квадрата, звучит несинхронно ПО СТРУКТУРЕ, даже
когда темп совпал идеально. Это и есть главный навык.

**Тональность.** Две тональности либо уживаются, либо дерутся. Колесо
Камелота сужает список кандидатов, но не решает за вас.

**Уровень.** Две деки складываются. Если оба трека звучат целиком, на
стыке получается горб; если развести их по частотам — не получается.

## Почему сводят эквалайзером, а не фейдером

Замер на двух днб-треках, кроссфейдер ровно в середине:

    оба трека целиком            +2.87 dB
    басовый обмен по полосам     +0.44 dB
    оба на единице, без фейдеров +5.88 dB, пик за нулём

Работает не «EQ вместо громкости» — EQ вообще плохой регулятор
громкости: килл низа роняет уровень на 1.9 dB, килл верха на 0.15, и
зависит это от того, что в треке. Работает **разведение по полосам**:
два трека, которые не лезут в одни и те же частоты, не складываются в
горб.

Отсюда правило обмена низом: у одного низ уходит ровно тогда, когда у
другого приходит, и плечи линейные — встречные кривые дают провал на
6 dB ровно в середине обмена.

## Где ставить точки

Уход — ближе к концу уходящего, вход — ближе к началу входящего, и оба
на границе фразы. Хороший уход: брейкдаун, яма, дроп, чистая граница
квадрата. Хороший вход: синхронный дроп, ведущее интро, преддроп.

Трек должен отыграть хотя бы две фразы. Меньше — это уже не трек, а
вставка, и сет рассыпается на обрывки.

## Осторожно

Автоанализ — это ОЦЕНКА, а не вердикт. Плохая фразировка, разрыв темпа,
конфликт вокалов или неверная энергия испортят переход, даже если все
метки совпали. Колесо сужает список, решение принимают уши.
"""


def _as_markdown(block: str) -> str:
    """Блок music_theory -> разметка.

    Блоки писались для системной подсказки ассистента, то есть обычным
    текстом: первая строка — название ЗАГЛАВНЫМИ, дальше проза и списки
    с отступом. Человеку такое нужно показать заголовком, а не строкой
    капсом посреди абзаца.

    Преобразование держится на том, что формат ровный: у каждого блока
    ровно одна строка заглавными и она первая (проверено по всем пяти).
    Если однажды это перестанет быть правдой, раздел не сломается —
    просто останется без заголовка."""
    lines = block.strip().split("\n")
    if not lines:
        return ""
    head = lines[0].strip()
    if head and head == head.upper() and len(head) > 4:
        title = head.capitalize()
        return "## " + title + "\n\n" + "\n".join(lines[1:]).strip()
    return block.strip()


def _from_music_theory() -> str:
    """Теория музыки — ровно та, что читает ассистент.

    Не пересказ: те же строки из music_theory.py. Пересказ разошёлся бы
    с оригиналом на первой же правке, и разошёлся бы молча."""
    import music_theory as mt

    parts = [
        "# Теория музыки\n",
        "Ровно то, что знает ассистент: эти же блоки идут ему в системную "
        "подсказку. Если здесь что-то поправить, изменится и его совет.\n",
    ]
    parts += [_as_markdown(b) for b in
              (mt.PHRASING, mt.CAMELOT, mt.SECTION_JUNCTIONS, mt.PERCUSSION, mt.STEMS)]
    return "\n\n".join(p.strip() for p in parts if p)


def _techniques_reference() -> str:
    """Справочник приёмов из живого словаря TECHNIQUES.

    Собирается при каждом запросе, а не пишется руками: приёмов
    шестьдесят три, и копия в markdown устарела бы на первой правке."""
    from techniques import TECHNIQUES

    by_cat: dict[str, list] = {}
    for tid, t in sorted(TECHNIQUES.items()):
        by_cat.setdefault(t.category or "прочее", []).append((tid, t))

    out = ["# Справочник приёмов\n",
           f"Всего {len(TECHNIQUES)}. Собрано из кода: то, что здесь написано, "
           f"и есть то, что приём делает.\n"]
    for cat in sorted(by_cat):
        out.append(f"\n## {cat}\n")
        for tid, t in by_cat[cat]:
            need = []
            if t.requires_stems:
                need.append("нужны слои")
            if t.requires_decks > 2:
                need.append(f"дек: {t.requires_decks}")
            if t.needs_vocals:
                need.append("нужен вокал")
            head = f"### {tid} · {t.name}"
            if need:
                head += f"  _({', '.join(need)})_"
            out.append(head)
            out.append(f"\nСложность {t.difficulty}/5. {t.description}\n")
            if t.steps:
                out.append("\n".join(f"{i}. {s}" for i, s in enumerate(t.steps, 1)))
            if t.params:
                out.append("\nНастройки: " + ", ".join(
                    f"{p.label} ({p.default:g} {p.unit})".strip() for p in t.params))
            out.append("")
    return "\n".join(out)


# Слаг -> (заголовок, как получить текст). Функцией, а не готовой
# строкой: справочник и теория собираются из кода на каждый запрос.
SECTIONS: dict[str, tuple] = {
    "guide": ("Руководство", lambda: GUIDE),
    "dj": ("Теория сведения", lambda: DJ_THEORY),
    "music": ("Теория музыки", _from_music_theory),
    "techniques": ("Справочник приёмов", _techniques_reference),
}


def index() -> list[dict]:
    return [{"slug": k, "title": v[0]} for k, v in SECTIONS.items()]


def page(slug: str) -> dict | None:
    item = SECTIONS.get(slug)
    if item is None:
        return None
    title, get = item
    try:
        text = get()
    except Exception as exc:                         # noqa: BLE001
        text = f"# {title}\n\nНе смог собрать этот раздел: {exc}"
    return {"slug": slug, "title": title, "markdown": text}
