"""
library_analysis.py — что именно нужно досчитать в библиотеке и в каком порядке.

## Зачем отдельный модуль

Во вкладке «Библиотека» было несколько независимых кнопок анализа и обслуживания.
Порядок между ними был неписаным —
стемы после скана, карты вокала после стемов, метки после всего, — и
нарушение порядка не ругалось, а молча давало неверный результат. Хуже
того, каждая кнопка считала СВОЁ заново целиком: добавить в папку один
трек стоило ровно столько же, сколько первый проход по всей библиотеке.

Здесь собрано то, что отвечает на два вопроса — «в каком порядке» и
«чего не хватает». Ровно эти две вещи и надо было проверять тестами, а
они жили внутри server.py, который в самопроверке не поднимается (он
тянет за собой FastAPI). Поэтому логика — тут,
а в server.py остались только запуск подпроцессов и рассылка прогресса в UI.

ВАЖНО про пропуск. Пропуск шага — это нормальный исход, а не ошибка:
«слои есть у всех 70 треков» и «не смог посчитать слои» должны выглядеть
по-разному, иначе диджей перестаёт читать отчёт вообще.
"""
from __future__ import annotations

import json
import os

# Порядок принудительный: он и есть та самая неписаная память, которую
# кнопки требовали от диджея. Клиент присылает НАБОР шагов, а не их
# последовательность — см. order_steps.
ANALYZE_STEPS = ("scan", "bpm", "stems", "vocals", "layers", "catalog", "cleanup")

ANALYZE_TITLES = {
    "scan": "Разбор треков",
    "bpm": "Темп и карты",
    "stems": "Разделение на слои",
    "vocals": "Карты вокала",
    "layers": "Признаки слоёв",
    "catalog": "Стили из каталогов",
    "cleanup": "Уборка мусора",
}

ANALYZE_WHY = {
    "scan": "темп, тональность, энергия, структура — только новые и изменившиеся файлы",
    "bpm": "перемер темпа и карты барабанов/энергии там, где они врут или их нет",
    "stems": "разделение на слои и сборка .stem.mp4 — без них половина техник падает на кроссфейд",
    "vocals": "где в треке звучит голос — флаг vocal у секций",
    "layers": "яркость барабанов и гармонии, плотность и полоса баса — по каждому слою отдельно; по ним подбор видит, чем два трека столкнутся",
    "catalog": "поджанр из MusicBrainz и Discogs там, где своего нет",
    "cleanup": "демо, сеты, записи и оборванные папки слоёв",
}

# Слои и карты вокала — ОТДЕЛЬНО, а не в наборе по умолчанию.
#
# На лендинге написано, что пакет слоёв (≈2,5 ГБ) необязателен, — и это
# правда для программы, но не было правдой для кнопки «Анализ
# библиотеки»: она считала слои всегда. На видеокарте это минуты, а на
# процессоре — минута-пять НА ТРЕК, то есть на 179 треках несколько
# часов молчаливой полосы. Человек нажимал «анализ» и не понимал,
# почему ничего не происходит.
#
# Теперь это осознанный выбор: галочки есть, но сняты, и рядом написано,
# на чём будет считаться и сколько это займёт.
ANALYZE_DEFAULT = ("scan", "bpm", "catalog", "cleanup")

# Шаги, которые просят пакет слоёв и потому включаются только руками.
#
# «layers» сам по себе не тяжёлый — он не считает нейросеть, а меряет уже
# готовые файлы (секунды на трек). В тяжёлых он потому, что БЕЗ СЛОЁВ ОН
# НЕ ДЕЛАЕТ НИЧЕГО: у трека без стемов мерить нечего. Ставить его в набор
# по умолчанию значило бы показывать «пропущено» всем, у кого пакета
# слоёв нет, — то есть большинству.
ANALYZE_HEAVY = ("stems", "vocals", "layers")

# Маркер машинной строки прогресса. ASCII — и это не вкусовщина.
#
# Он был кириллическим, и на stdout, который кириллицу не кодирует,
# строка прогресса не могла быть напечатана ВООБЩЕ: ни целиком, ни
# с экранированным именем файла — префикс ломался первым. Маркер
# машинного протокола человек не читает (эти строки нарочно не
# попадают в хвост для глаз), так что кириллица в нём не давала
# ничего, кроме одного лишнего способа остаться без прогресса.
PROGRESS_PREFIX = "[PROGRESS] "


def order_steps(want) -> list[str]:
    """Набор шагов -> наша последовательность.

    Клиент присылает, ЧТО делать; в каком порядке — решаем здесь. Иначе
    порядок снова оказывается на совести того, кто нажимает кнопку."""
    chosen = set(want or ())
    return [k for k in ANALYZE_STEPS if k in chosen]


def parse_progress_line(line: str) -> dict | None:
    """Машинная строка прогресса от stems.py (см. stems.emit_progress).

    Прогресс идёт машинной строкой, а не разбором человеческого вывода:
    подпроцесс печатает и «[3/13] имя — 41с», и предупреждения, и JSON
    отчёта, и регулярка по ним ломалась бы от каждой правки текста."""
    if not isinstance(line, str) or not line.startswith(PROGRESS_PREFIX):
        return None
    try:
        d = json.loads(line[len(PROGRESS_PREFIX):])
    except (ValueError, TypeError):
        return None
    if not isinstance(d, dict) or "total" not in d or "i" not in d:
        return None
    return d


def blank_status(steps: list[str]) -> dict:
    return {
        "running": True, "current": None, "finished_at": None,
        "steps": [{"key": k, "title": ANALYZE_TITLES.get(k, k),
                   "why": ANALYZE_WHY.get(k, ""), "state": "wait",
                   "done": 0, "total": 0, "note": "", "name": ""}
                  for k in steps],
    }


def common_root(paths) -> str:
    """Общий корень путей библиотеки — папка, с которой диджей работает.

    Нужен фоновому анализу, когда путь не передан отдельным параметром."""
    real = [p for p in (paths or []) if p]
    if not real:
        return ""
    try:
        return str(os.path.commonpath(real))
    except (ValueError, TypeError):
        return ""


def missing_report(tracks, has_stems=None, vocal_map=None,
                   layer_features=None, has_layers=None) -> dict:
    """Чего не хватает библиотеке — по одному числу на шаг.

    Считается ДО запуска и показывается на кнопке: «анализ нужен вот
    этим 12 трекам» честнее, чем «анализ» без числа, после которого
    непонятно, будет это минута или ночь.

    has_stems/vocal_map/layer_features передаются снаружи (из stems.py и
    stem_features.py), чтобы модуль не тянул за собой numpy и torch ради
    четырёх счётчиков."""
    tracks = list(tracks or [])
    paths = [t.get("path") for t in tracks if t.get("path")]
    out = {"tracks": len(tracks)}

    # Темп-заглушка. Признак был такой: «одинаковый BPM у многих треков
    # — это не измерение». Он неверен для жанровых библиотек. У диджея
    # 15 треков из 140 стоят на 174.0 — это не заглушка, это драм-н-бейс,
    # где 174 канонический темп. Счётчик показывал 15 всегда, шаг
    # запускался всегда и менял 0 треков.
    #
    # Заглушка — это когда ОДНО значение занимает БОЛЬШУЮ ЧАСТЬ
    # библиотеки: так выглядит темп, проставленный по умолчанию. Порог
    # больше половины: жанр столько не занимает даже в моностилевой
    # подборке, потому что треки всё равно расходятся на 173/174/175.
    bpms = [round(float(t.get("bpm") or 0), 1) for t in tracks if t.get("bpm")]
    same = max((bpms.count(b) for b in set(bpms)), default=0)
    out["bpm"] = same if len(bpms) > 4 and same > len(bpms) * 0.5 else 0
    # Трек вообще без темпа считать надо всегда: это не спорный признак.
    out["bpm"] += sum(1 for t in tracks if not (float(t.get("bpm") or 0) > 0))
    out["maps"] = sum(1 for t in tracks
                      if not ((t.get("structure") or {}).get("drum_map"))
                      or not ((t.get("structure") or {}).get("energy_map")))

    if has_stems is not None:
        no_stems = [p for p in paths if not has_stems(p)]
        out["stems"] = len(no_stems)
        # Карты вокала и признаки слоёв считаются ТОЛЬКО по папке слоёв:
        # им нужны четыре файла, и записывать результат тоже некуда,
        # кроме meta.json в этой папке.
        #
        # Считаем по has_stems — то есть и по голому .stem.mp4 рядом с
        # треком. Так было НЕ всегда, и история тут поучительная:
        #
        #   1. Сначала стоял has_stems, а записать разметку для mp4 было
        #      некуда: обе карты пишутся в meta.json внутри папки слоёв.
        #      Счётчики показывали «вокал 54, слои 127» и не могли дойти
        #      до нуля никогда — шаг честно пропускал эти треки.
        #   2. Тогда счёт сузили до has_layers: счётчики стали честными,
        #      но 54 трека остались без разметки навсегда.
        #   3. Теперь разметка для них ложится файлом-спутником рядом с
        #      mp4 (stems.write_meta), и считать их снова МОЖНО.
        #
        # То есть исправление не в счётчике, а в том, что появилось куда
        # писать. Счётчик просто перестал это скрывать.
        ready = [p for p in paths if has_stems(p)]
        if vocal_map is not None:
            out["vocals"] = sum(1 for p in ready if vocal_map(p) is None)
        if layer_features is not None:
            out["layers"] = sum(1 for p in ready if layer_features(p) is None)
        # Строка «только mp4» остаётся: знать, у скольких треков слоёв
        # нет на диске, полезно и теперь — разделение даёт лучшее
        # качество и позволяет резать слои по отдельности.
        if has_layers is not None:
            out["mp4_only"] = sum(1 for p in paths
                                  if has_stems(p) and not has_layers(p))
    out["catalog"] = sum(1 for t in tracks
                         if not ((t.get("meta") or {}).get("sources")))
    return out
