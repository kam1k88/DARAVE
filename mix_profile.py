"""
mix_profile.py — ручное ведение двух фейдеров, ОДНО на все тракты.

## Зачем отдельный модуль

Профиль ввода («входящий: за сколько поднять», «ход», «уходящий:
сколько уводить», «ход») жил внутри `demo_render` — то есть применялся
только к офлайн-рендеру одиночного демо. Отсюда и расхождение, которое
диджей описал точнее любого лога: «когда ставишь вручную — сводит
красиво, причём любые тактики; а в пуле те же клипы снова звучат
разрозненно, входящий не накладывается на уходящий».

Разрозненно они звучали потому, что профиля там не было вовсе: пул
рендерился без него, сет собирался без него, живое исполнение в Mixxx о
нём не знало. Три тракта считали одно и то же по-разному.

Профиль — это преобразование СПИСКА СОБЫТИЙ, а не звука: он выбрасывает
кроссфейд приёма и заменяет его двумя независимыми фейдерами. Значит
применять его можно ровно там же, где события и живут, — и офлайн, и
живьём. Поэтому он и вынесен сюда: `demo_render`, `mix_strategist`
(живое исполнение) и `set_export` зовут одну и ту же функцию.

## Что делают четыре числа

* `in_len` — за какую долю перехода входящий доходит до полного;
* `in_smooth` — каким ходом он это делает;
* `out_len` — сколько длится увод уходящего;
* `out_smooth` — каким ходом уводится он.

Уходящий стоит на месте до `1 - out_len`, потом уходит. Если
`in_len + out_len < 1`, между ними получается площадка, где ОБА трека
звучат полноценно — то, что диджей называет наложением. Если сумма
больше единицы, они пересекаются — обычный кроссфейд. Одна механика,
разные числа.

`entry: "technique"` (или пустой профиль) — не трогаем ничего, форму
ведёт сам приём.

## Почему это не то же самое, что кроссфейд

Один фейдер едет из нуля в единицу, и в середине обе деки звучат
вполовину. Диджей ведёт иначе: новый трек поднимается РЯДОМ с ещё
полным старым, и только потом старый уводится. Это два независимых
фейдера, а не один.
"""
from __future__ import annotations

from techniques import _ramp as _mk_ramp

# Значения по умолчанию. Это НЕ подобранные «на глаз» числа: диджей нашёл
# их сам и описал диапазоны, в которых «получается чистый фейдер при
# любой технике сведения» — входящий поднимается за 75-90% перехода,
# уходящий уводится за последние 15-25%. Берём середины.
DEFAULTS = {"in_len": 0.85, "in_smooth": 0.3, "out_len": 0.20, "out_smooth": 0.5}

RAMP_STEPS = 8


def _clamp(v: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, float(v)))


def is_manual(profile: dict | None) -> bool:
    """Профиль ведёт фейдеры сам (а не отдаёт форму приёму)?"""
    return str((profile or {}).get("entry") or "technique") != "technique"


def fader_shape(x: float, smooth: float) -> float:
    """Форма хода фейдера: 0 — рывком в начале, 1 — долгий разгон.

    Одна ручка вместо кривой: `smooth` меняет показатель степени от 0.4
    (фейдер сразу набирает и потом доводит) до 2.5 (долго почти ничего,
    потом быстро). 0.5 посередине — почти линейно, как и ведут руками."""
    g = 0.4 * (2.5 / 0.4) ** _clamp(smooth, 0.0, 1.0)
    return float(_clamp(x, 0.0, 1.0) ** g)


def ramp_curve(t0: float, span: float, action: str, deck: str,
               v0: float, v1: float, smooth: float,
               steps: int = RAMP_STEPS) -> list[dict]:
    """Ход фейдера заданной формы — ломаной из нескольких отрезков.

    Обычная рампа умеет только прямую между двумя значениями, а форма —
    это как раз то, что отличает «завёл и повёл» от «выкрутил и ждёшь»."""
    out = []
    span = max(0.5, float(span))
    for i in range(steps):
        a, b = i / steps, (i + 1) / steps
        out.append(_mk_ramp(t0 + span * a, action, deck, span / steps,
                            v0 + (v1 - v0) * fader_shape(a, smooth),
                            v0 + (v1 - v0) * fader_shape(b, smooth)))
    return out


def apply(events: list[dict], profile: dict | None,
          target_deck: str = "target", source_deck: str = "source") -> list[dict]:
    """Заменить кроссфейд приёма ручным ведением двух фейдеров.

    Работает над готовыми событиями, поэтому одинаково годится и для
    офлайн-рендера (там события уже подогнаны под окно перехода), и для
    живого исполнения (там они идут как есть).

    ИМЕНА ДЕК — обязательный аргумент: офлайн-рендер знает деки как
    «source» и «target», живой план — как настоящие A/B. Пока профиль
    подставлял свои имена, живьём он падал на неизвестной деке.

    Кроссфейдер здесь не участвует вообще — обе деки ведутся фейдерами
    своих каналов (см. ниже, почему это принципиально)."""
    profile = profile or {}
    if not is_manual(profile):
        return events
    if str(profile.get("entry")) == "overlay":     # прежнее имя набора
        profile = {**DEFAULTS, **profile}

    in_len = _clamp(profile.get("in_len", DEFAULTS["in_len"]), 0.05, 1.0)
    out_len = _clamp(profile.get("out_len", DEFAULTS["out_len"]), 0.05, 1.0)
    in_smooth = _clamp(profile.get("in_smooth", profile.get("rise", 0.5)), 0.0, 1.0)
    out_smooth = _clamp(profile.get("out_smooth", DEFAULTS["out_smooth"]), 0.0, 1.0)
    if not events:
        return events

    others = [e for e in events if e["action"] not in ("crossfade", "volume_ramp")]
    t0 = min(e["beat_offset"] for e in events)
    t1 = max(e["beat_offset"] + float(e.get("duration_beats") or 0.0) for e in events)
    span = max(4.0, t1 - t0)
    out_start = t0 + span * (1.0 - out_len)

    out = list(others)
    # Входящий: свой фейдер канала, от нуля до полного за in_len.
    out += ramp_curve(t0, span * in_len, "volume_ramp", target_deck, 0.0, 1.0, in_smooth)
    out.append(_mk_ramp(t0 + span * in_len, "volume_ramp", target_deck,
                        max(0.5, span * (1.0 - in_len)), 1.0, 1.0))
    # Уходящий: тоже СВОИМ фейдером канала, а не кроссфейдером.
    #
    # Раньше он уводился кроссфейдером, и это было ошибкой — той самой,
    # из-за которой «по приёму сводит некрасиво, а вручную красиво».
    # Кроссфейдер в Mixxx проходит через выбранную кривую (равной
    # мощности или аддитивную), и эта кривая рассчитана на СОВМЕСТНОЕ
    # ведение двух дек одним фейдером: она поднимает одну ровно настолько,
    # насколько опускает другую. Здесь же деки ведутся НЕЗАВИСИМО, и
    # входящий к моменту увода уже стоит на полном. Компенсировать
    # нечего, а кривая всё равно компенсирует — отсюда и «грязь».
    #
    # Два фейдера каналов дают ровно то, что диджей и описывает как
    # чистый фейдер: линейную амплитуду, без чужой математики поверх. И
    # кривая кроссфейдера в настройках Mixxx на такое сведение больше не
    # влияет вовсе.
    out.append(_mk_ramp(t0, "volume_ramp", source_deck,
                        max(0.5, span * (1.0 - out_len)), 1.0, 1.0))
    out += ramp_curve(out_start, span * out_len, "volume_ramp", source_deck,
                      1.0, 0.0, out_smooth)
    out.sort(key=lambda e: e["beat_offset"])
    return out


def from_overrides(ov: dict | None) -> dict | None:
    """Профиль, приехавший с правками перехода (из отбора или плана)."""
    if not ov:
        return None
    profile = ov.get("mix_profile") or (ov.get("params") or {}).get("mix_profile")
    return profile if is_manual(profile) else None


# --------------------------------------------------- два режима ведения
#
# Диджей предложил разделить донастройку перехода на два режима, и это
# правильное деление — оно проходит ровно по границе «кто держит форму».
#
#   "technique" — РЕКОМЕНДУЕМЫЙ. Форму ведёт приём: он и кроссфейдер, и
#                 EQ, и FX, и слои. Ничего не спрашиваем.
#   "manual"    — КАСТОМНЫЙ. Фейдеры каналов ведёт диджей, всё
#                 остальное (EQ, FX, стемы, обмен низом) по-прежнему
#                 ведёт приём и подстраивается под точки само.
#
# Почему манипуляторов ровно четыре, а не двадцать.
#
# Диджей спросил прямо: какие настройки лучше вынести? Ответ выводится
# из того, что рука диджея на пульте физически делает во время сведения.
# Она делает три вещи: ведёт фейдер входящего, ведёт фейдер уходящего и
# выбирает, сколько это длится. Всё остальное — EQ, фильтр, эхо, слои —
# либо стоит на месте, либо является ПРИЁМОМ, то есть тем, что мы уже
# выбрали в списке. Выносить это в ручные ручки значит предлагать
# собрать технику заново вместо того, чтобы выбрать готовую.
#
# ХРАНИМ В ДОЛЯХ, ПОКАЗЫВАЕМ В ТАКТАХ. Это не мелочь интерфейса.
# Диджей просил, чтобы «настройки при смене техники и точек входа
# адаптировались сами» — а доля от длины перехода как раз и
# адаптируется: сменил 16 тактов на 32, и «входящий доходит за 85%»
# по-прежнему означает то же самое движение руки. Такты не
# адаптируются: 14 тактов в переходе на 16 и в переходе на 32 — разные
# жесты. Но думает и слышит диджей в тактах, поэтому показываем такты, а
# пересчитываем их при каждой смене длины.

MODES = ("technique", "manual")

# Форма хода фейдера. Три именованных варианта вместо числа 0..1:
# число описывает то же самое, но им нельзя объяснить, что слышно.
SHAPES = {
    # Рука идёт ровно — так ведут чаще всего, и так фейдер предсказуем.
    "linear":  {"value": 0.5, "name": "линейно",
                "hint": "фейдер идёт с одной скоростью"},
    # Быстро взять и медленно довести. Входящий заявляет о себе сразу, а
    # последние децибелы добираются долго — наложение получается мягким.
    "fast":    {"value": 0.15, "name": "с ускорением",
                "hint": "сразу набирает, к концу замедляется"},
    # Долго почти ничего, потом быстро. Для увода: уходящий держится, а
    # потом исчезает — так уводят под дроп входящего.
    "slow":    {"value": 0.85, "name": "с торможением",
                "hint": "сначала почти стоит, в конце уходит быстро"},
}


def shape_value(name_or_value) -> float:
    """Имя формы или само число — на выходе всегда число."""
    if isinstance(name_or_value, str) and name_or_value in SHAPES:
        return float(SHAPES[name_or_value]["value"])
    try:
        return _clamp(float(name_or_value), 0.0, 1.0)
    except (TypeError, ValueError):
        return 0.5


def shape_name(value: float) -> str:
    """Ближайшая именованная форма — чтобы интерфейс показал слово."""
    v = _clamp(value, 0.0, 1.0)
    return min(SHAPES, key=lambda k: abs(SHAPES[k]["value"] - v))


def describe(profile: dict | None, bars: float | None = None) -> dict:
    """Профиль в том виде, в каком его показывают диджею.

    Возвращает и доли (как хранится), и такты (как читается), и имена
    форм. `bars` — длина перехода; без неё такты не считаются, и это
    честно: «за сколько тактов» без «из скольких» ничего не значит."""
    prof = {**DEFAULTS, **(profile or {})}
    mode = "manual" if is_manual(profile) else "technique"
    in_len = _clamp(prof.get("in_len", DEFAULTS["in_len"]), 0.05, 1.0)
    out_len = _clamp(prof.get("out_len", DEFAULTS["out_len"]), 0.05, 1.0)
    in_sh = shape_value(prof.get("in_smooth", DEFAULTS["in_smooth"]))
    out_sh = shape_value(prof.get("out_smooth", DEFAULTS["out_smooth"]))
    # Площадка — то, ради чего всё и затевалось: сколько времени оба
    # трека звучат полноценно. Отрицательная означает обычный кроссфейд,
    # где один уходит раньше, чем другой пришёл.
    overlap = 1.0 - in_len - out_len
    out = {
        "mode": mode,
        "in_len": round(in_len, 3), "out_len": round(out_len, 3),
        "in_smooth": round(in_sh, 3), "out_smooth": round(out_sh, 3),
        "in_shape": shape_name(in_sh), "out_shape": shape_name(out_sh),
        "overlap_fraction": round(overlap, 3),
    }
    # Предупреждение, которое стоит показать: при in_len + out_len >= 1
    # площадки нет вовсе — уходящий начинает уходить раньше, чем
    # входящий дошёл до полного. Это уже кроссфейд, пусть и двумя
    # руками. На значениях по умолчанию (0.85 + 0.20) так и выходит:
    # площадка −5%, то есть деки пересекаются на 5% длины перехода.
    if overlap < -0.005:
        out["note"] = ("уходящий начинает уходить раньше, чем входящий дошёл "
                       "до полного — площадки наложения нет, это кроссфейд "
                       "двумя руками")
    elif overlap < 0.01:
        out["note"] = "входящий доходит до полного ровно к началу увода"
    if bars:
        b = float(bars)
        out["bars"] = b
        out["in_bars"] = round(b * in_len, 1)
        out["out_bars"] = round(b * out_len, 1)
        out["out_starts_at_bar"] = round(b * (1.0 - out_len), 1)
        out["overlap_bars"] = round(b * overlap, 1)
        out["summary"] = (
            f"вход за {out['in_bars']:g} т., "
            f"увод с {out['out_starts_at_bar']:g}-го такта ({out['out_bars']:g} т.), "
            + (f"оба полноценно {out['overlap_bars']:g} т."
               if overlap > 0.01 else "площадки наложения нет")
        )
    return out


def from_bars(bars: float, in_bars: float, out_bars: float,
              in_shape="linear", out_shape="linear") -> dict:
    """Собрать профиль из тактов — обратная сторона describe().

    Интерфейс спрашивает такты, хранилище получает доли: при смене длины
    перехода доли останутся верными, а такты пересчитаются сами."""
    b = max(1.0, float(bars))
    return {
        "entry": "manual",
        "in_len": _clamp(float(in_bars) / b, 0.05, 1.0),
        "out_len": _clamp(float(out_bars) / b, 0.05, 1.0),
        "in_smooth": shape_value(in_shape),
        "out_smooth": shape_value(out_shape),
    }
