"""
music_theory.py — та музыкальная грамота, без которой совет «своди здесь»
остаётся угадыванием.

Справка написана диджеем и лежит здесь одним куском по двум причинам.
Первая: её читает ассистент (agent.py подставляет `for_agent()` в
системную подсказку), и правка справки меняет поведение агента без правки
кода. Вторая: те же правила уже зашиты в планировщик — фразировка в
`mix_points.py`, Camelot в `mix_strategist.py`, — и держать их словесную
формулировку рядом полезно: расхождение кода и справки видно сразу.

Главное, что отсюда следует для агента: колесо Камелота и сетка тактов
СУЖАЮТ список кандидатов, но не выносят вердикт. Автоанализ тональности —
оценка, а не истина.
"""
from __future__ import annotations

PERCUSSION = """\
ПЕРКУССИЯ И ДОЛИ
Kick (бочка) — низкий удар, основа ритма. Snare (малый) — резкий акцент.
Hi-hat — высокое «тссс», заполняет пространство. Clap, томы, перкуссия,
райд — дополняют грув. В драм-н-бейсе сердце жанра — брейкбит: kick плюс
snare, причём snare на 2-й и 4-й доле.

В такте 4/4 четыре доли:
  1 — сильная (downbeat), там kick;
  2 — слабая, snare;
  3 — относительно сильная, kick;
  4 — слабая, snare.
Offbeat — между долями (хэт), он и делает грув.
Сильные доли — якоря для сведения. Слабые — место для ввода нового трека.
"""

PHRASING = """\
КВАДРАТ (ФРАЗИРОВКА)
  1 такт  = 4 доли
  1 фраза = 4 такта  (16 долей)
  1 квадрат = 8 тактов (32 доли)   — стандарт для диджея
  мега-квадрат = 16-32 такта       — для длинных переходов

Правила:
  * ввод нового трека — на границе квадрата (8 или 16 тактов);
  * смена секции (дроп, брейкдаун) — на границе квадрата;
  * переход между треками — один-два квадрата (8-16 тактов);
  * дроп — начало квадрата.
Переход, начатый не на границе квадрата, звучит несинхронно по СТРУКТУРЕ,
даже когда BPM совпадает идеально. Это и есть фразировка — ключевой навык.
"""

CAMELOT = """\
КОЛЕСО КАМЕЛОТА
24 тональности: номер 1-12 плюс буква (A — минор, B — мажор). A minor =
8A, C major = 8B, E minor = 9A. Родственно квинтовому кругу, но с
диджейской нумерацией.

Три безопасных перехода:
  * тот же сектор (8A -> 8A) — тональность сохраняется целиком; годится
    для длинного мелодичного наложения;
  * соседний номер, та же буква (8A -> 7A или 9A, 12 и 1 смыкаются) —
    гармония сохраняется; плавный подъём или спад;
  * та же цифра, другая буква (8A -> 8B) — общие ноты, но меняется
    настроение; это смена эмоции, минор против мажора.

Как их играют:
  8A -> 9A: синхронизировать темп; зайти на начало 16- или 32-тактовой
  фразы; сперва барабаны, потом бас; закрыть бас уходящего и открыть бас
  входящего; держать синт исходной тональности, пока мотив не кончится.
  8A -> 8B: перкуссивное интро мажорного трека под брейк минорного;
  замена баса на новой фразе; мажорный хук открывать только после ухода
  минорной мелодии. Два вокала одновременно — конфликт.

Прыжки на два номера, полутоны и далёкие секторы — это ИНСТРУМЕНТЫ
НАПРЯЖЕНИЯ, а не безопасные правила. Делать их через барабанный луп,
уход в эхо или чистый кат на downbeat.

Осторожно: разные программы показывают тональность по-разному, а
автоанализ — это ОЦЕНКА, а не вердикт. Плохая фразировка, разрыв темпа,
конфликт вокалов или неверная энергия испортят переход, даже если метки
совпали. Колесо сужает список кандидатов, решение принимают уши.
"""



SECTION_JUNCTIONS = """\
СЕКЦИИ, ИХ НАЗВАНИЯ И СТЫКИ

DARAVE размечает трек ШЕСТЬЮ секциями, и называются они по-английски:
  intro       до первой доли с барабанами; сюда заводят трек
  build       последняя фраза перед дропом: напряжение растёт
  drop        кульминация, полная аранжировка
  breakdown   разрядка: низ и барабаны убраны
  groove      тело трека между событиями
  outro       барабаны кончились; отсюда уводят

Слова «куплет» в этом списке нет, и это не придирка к переводу. Куплет —
термин песенных жанров: он предполагает вокал с РАЗНЫМ текстом от куплета
к куплету. В электронной музыке тело трека называется groove, а вокал
чаще всего зациклённый сэмпл, а не спетый куплет. Секции verse у DARAVE
тоже нет по той же причине.

ВОКАЛ — ЭТО ПРИЗНАК СЕКЦИИ, А НЕ СЕКЦИЯ. У каждой секции есть флаг
vocal: groove с вокалом остаётся groove, вокальный дроп остаётся drop.
Так и должно быть: голос не меняет роли секции в аранжировке, он меняет
то, что с ней можно сделать на сведении. Два голоса одновременно —
конфликт, а не наложение; голос только у одного из треков — наоборот,
лучший материал для перехода.

СТЫК — точка, где кончается одна секция и начинается другая. Приём
выбирается ПОД СТЫК, а не под трек.
  drop -> breakdown   основной ход почти везде: убрали кик и бас,
                      осталась атмосфера. Готовит второй дроп.
  breakdown -> drop   самый сильный подъём; в EDM почти всегда через билд.
  drop -> drop        двойной дроп. Требует совместимых тональностей либо
                      разведения по слоям: два баса не складываются.
  groove -> groove    рабочая лошадь сета, на ней он и держится.
  breakdown -> breakdown   место для длинного бленда и акапеллы.
  groove -> drop      тело ведёт прямо в полный бит.
  drop -> groove      спад после кульминации без ухода в брейкдаун.

BUILD как связка. «Стык с билдом» — не отдельный тип перехода, а группа,
где билд стоит мостом между секциями:
  breakdown -> build -> drop   канон EDM и драм-н-бейса;
  drop -> build -> drop        путь ко второму дропу.
В драм-н-бейсе билд короткий, 4-16 тактов: снейр-ролл, riser, фильтр,
реверс-сэмпл, пауза перед дропом. В трансе это отдельная секция на 16-32
такта. В биг-бите бывает 1-2 такта.

ВТОРОЙ ДРОП СИЛЬНЕЕ ПЕРВОГО — это правило аранжировки, а не случайность:
первый дроп заявляет тему, второй её добивает, поэтому у него больше
слоёв и обработки. Уходить с трека лучше со второго дропа.

ЧТО ЕЩЁ НАЗЫВАЮТ СЕКЦИЯМИ В РАЗНЫХ СТИЛЯХ (у DARAVE этих ролей нет, но
диджей их называет, и понимать их надо):
  mid section     16-32 такта между первым дропом и брейкдауном:
                  вариация — одни барабаны или другой бас. Драм-н-бейс.
  switch-up,      смена паттерна внутри дропа без ухода энергии: тот же
  rollout         дроп, другой ритм. Драм-н-бейс, джангл.
  second drop     он же drop 2 — см. выше.
  bridge          одиночная секция под конец трека, музыкально не похожая
                  ни на что вокруг. Песенные жанры, гэридж, вокальный хаус.
  verse, chorus,  песенная схема. Встречается в гэридже, вокальном хаусе,
  hook            хип-хопе, но не в драм-н-бейсе.
  interlude       короткая связка без бита между частями. Транс, техно.
  riser, fill,    не секции, а события ВНУТРИ билда: подъём, сбивка,
  turnaround      разворот в конце фразы.
  half-time       секция, где барабаны играют вдвое реже при том же темпе.
                  Драм-н-бейс, дабстеп, нейрофанк.
  main room       трансовое название дропа: часть после брейкдауна, где
                  играет всё.

ДЛИНА КВАДРАТА ЗАВИСИТ ОТ ЖАНРА, и это не мелочь:
  биг-рум, phonk        4-16 тактов
  драм-н-бейс, дабстеп  8-32
  ликвид, хаус, техно, транс   16-64
Транс живёт брейкдаунами на 64-96 тактов, phonk — целиком короче одного
трансового брейкдауна. Одна сетка фраз на все стили одинаково врёт и там
и там.
"""

STEMS = """\
СТЕМЫ: ЧТО ОНИ РЕШАЮТ
Стемы — не украшение перехода, а инструмент против конкретного
конфликта. Поводов ровно четыре:
  * два вокала сразу — снять вокальный слой уходящего;
  * два баса сразу — оставить бас одного вместо вырезания полосы
    эквалайзером (полоса нужна обоим, а инструмент — только одному);
  * нужно напряжение — оставить одни барабаны на 8-16 тактов перед дропом;
  * разрыв в тональности — наложить только ритмические части, убрав
    мелодию или вокал.

Стемы НЕ отменяют колесо Камелота, а сужают его действие: тональность
говорит, какие слои можно накладывать, стемы позволяют наложить только
их. Декорировать стемами каждый переход не нужно: основной ход и так
заводит новый трек его интро, где спорить нечем.

Цена: разделение смазывает тарелки и оставляет призрачный бас. Слой,
который в переходе не звучит, этих артефактов и не принесёт — ещё одна
причина трогать стемами только то, что мешает.
"""

def for_agent() -> str:
    """Блок для системной подсказки ассистента."""
    return "\n".join((PERCUSSION, PHRASING, SECTION_JUNCTIONS,
                      CAMELOT, STEMS)).strip()
