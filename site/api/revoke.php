<?php
declare(strict_types=1);
require_once __DIR__ . '/_auth.php';

/**
 * Отвязать компьютер.
 *
 * ВАЖНО про хеширование. `me.php` отдаёт device_id УЖЕ в том виде, в
 * каком он лежит в базе — то есть хешированным: хеширует его verify.php
 * в момент спаривания. Если хешировать его здесь второй раз, UPDATE не
 * найдёт ни одной строки, вернёт ok и не сделает ничего. Кнопка при этом
 * выглядит рабочей, список после перезагрузки не меняется, и человек
 * жмёт её снова и снова. Поэтому значение используется как есть.
 *
 * Отвязка не удаляет строку, а ставит revoked = 1: так в базе остаётся
 * след, с какого компьютера работали, и повторное подключение того же
 * компьютера просто снимет флаг (см. ON DUPLICATE KEY в verify.php).
 */

cors();
require_post();

$u  = require_user();
$in = body();
$device = trim((string)($in['device_id'] ?? ''));

// Формат тот же, что пишет verify.php: 64 шестнадцатеричных символа.
// Проверка не ради безопасности (запрос и так ограничен своим
// пользователем), а чтобы опечатка не уходила в базу молча.
if ($device === '' || !preg_match('/^[0-9a-f]{64}$/', $device)) {
    json_out(['error' => 'Не указано устройство'], 400);
}

$st = db()->prepare(
    'UPDATE devices SET revoked = 1 WHERE user_id = ? AND device_id = ? AND revoked = 0'
);
$st->execute([(int)$u['id'], $device]);

if ($st->rowCount() === 0) {
    // Честный ответ вместо бодрого «готово»: либо устройство уже
    // отвязано, либо это чужой идентификатор.
    json_out(['ok' => false, 'error' => 'Такое устройство у вас не числится или уже отвязано'], 404);
}

json_out(['ok' => true, 'revoked' => $device]);
