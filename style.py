# `claude/sections-and-style.md`. Но на выбор приёма он влияет, и сильно:
# два голоса одновременно это конфликт, а не наложение. Разница с
# Camelot в том, что тональность сужает, ЧТО можно накладывать, а вокал
# говорит, что накладывать нельзя ВООБЩЕ — голос занимает то самое место
# в спектре и во внимании, которое второй голос тоже требует.
#
# Приёмы, которые конфликт решают, а не прячут: передача вокала (один
# замолкает, другой начинает), снятие вокального слоя стемами, уход в
# эхо. Приёмы, которые его усугубляют: длинное тональное наложение.
VOCAL_HANDOVER = frozenset({"ST-15", "ST-13", "ST-06", "SF-03", "ST-09"})
VOCAL_BLEND = frozenset({"DNB-25", "SE-01", "ST-10", "ST-03", "SF-05", "ST-02"})


# --------------------------------------------------- расстройка от подгонки темпа
#
# Колесо Камелота считает тональности ПО МЕТКАМ, а метка не меняется, пока
# трек не уехал на целый полутон. Между тем подгонка темпа скоростью
# двигает высоту непрерывно: 171 к 175 — это 40 центов, почти половина
# полутона. Формально пара «8A -> 8A», фактически два расстроенных
# унисона, которые бьются на каждой длинной ноте.
#
# Поэтому у приёмов появляется вторая тональная поправка. Первая
# (key_technique_bias) смотрит на метки, эта — на то, что с ними сделает
# темп. Штрафуются те же приёмы, что и при разрыве по Камелоту, и по той
# же причине: длинное наложение тональных частей обнажает расстройку, а
# рез, обмен низом или работа по слоям — нет.
DETUNE_TOLERANT = frozenset({"DNB-22", "DNB-23", "DNB-24", "ST-07", "ST-08",
                             "ST-12", "ST-13", "SF-04", "DNB-20"})


def detune_technique_bias(tid: str, cents: float,
                          stems_ok: bool = False) -> tuple[float, str]:
    """Поправка к весу приёма за расстройку между деками.

    cents — расхождение по высоте после приведения к общему темпу
    (`tempo.detune_between`). Приёмы, которые держат треки вместе
    мелодически, дешевеют; резовые и послойные не трогаются вовсе — им
    расстройка не мешает, они не держат унисон."""
    import tempo as _tempo

    c = float(cents or 0.0)
    if c < _tempo.DETUNE_AUDIBLE_CENTS:
        return 1.0, ""
    if tid in DETUNE_TOLERANT:
        return 1.15, (f"темпы разъедут высоту на {c:.0f} центов, "
                      f"но приём не держит треки в унисоне")
    if tid in KEY_SAFE:
        return 1.10, ""
    hard = c >= _tempo.DETUNE_BROKEN_CENTS
    if tid in KEY_SENSITIVE:
        mult = (0.55 if hard else 0.75) if not stems_ok else (0.75 if hard else 0.9)
        return mult, (f"подгонка темпа разведёт высоту на {c:.0f} центов, "
                      f"а приём наложит тональные части"
                      + (" — часть можно снять стемами" if stems_ok else ""))
    return (0.75 if hard else 0.9), (
        f"подгонка темпа разведёт высоту на {c:.0f} центов")


def section_vocal(section: dict | None) -> bool:
    """Звучит ли в этой секции голос. Флаг ставит сегментация."""
    return bool((section or {}).get("vocal"))


def vocal_technique_bias(tid: str, a_vocal: bool, b_vocal: bool,
                         stems_ok: bool = False) -> tuple[float, str]:
    """Поправка на вокал: множитель к весу приёма и объяснение.

    Конфликт возникает ТОЛЬКО когда голос звучит с обеих сторон. Вокал у
    одного из треков — это не проблема, а наоборот материал: голос
    уходящего поверх инструментала входящего и есть самый красивый ход в
    ликвиде."""
    if not (a_vocal and b_vocal):
        return 1.0, ""
    if tid in VOCAL_HANDOVER:
        return 1.30, "голос с обеих сторон — приём передаёт вокал, а не смешивает"
    if tid in VOCAL_BLEND:
        # Стемы смягчают: вокальный слой уходящего можно просто снять.
        return (0.80 if stems_ok else 0.60), (
            "голос с обеих сторон, а приём держит треки вместе"
            + (" — спасают стемы" if stems_ok else ": два вокала столкнутся"))
    return 1.0, ""


def key_technique_bias(tid: str, distance: int | None,
                       stems_ok: bool = False) -> tuple[float, str]:
    """Множитель приёму по тональному расстоянию пары.

    `distance` — camelot_distance(a, b); None означает «тональность
    неизвестна», и тогда мы молчим: автоанализ тональности это оценка, а
    не вердикт, и наказывать приём за неизвестность нельзя.

    `stems_ok` — есть ли стемы у обоих треков. Стемы не отменяют Camelot,
    но смягчают его: конфликтующий тональный слой можно просто не
    накладывать, и приём остаётся играбельным.
    """
    if distance is None:
        return 1.0, ""
    if distance < KEY_CONFLICT_DISTANCE:
        if tid in KEY_SENSITIVE:
            return 1.15, "тональности сходятся — наложение прозвучит чисто"
        return 1.0, ""
    if tid in KEY_SENSITIVE:
        mult = 0.75 if stems_ok else 0.55
        why = ("тональности расходятся — длинное наложение обнажит разрыв"
               + ("; стемами конфликтующий слой можно снять" if stems_ok else ""))
        return mult, why
    if tid in KEY_SAFE:
        return 1.25, "тональности расходятся — приём не держит их вместе"
    return 1.0, ""


# --------------------------------------------------------- фразы по жанру
#
# «В разных стилях существуют свои квадраты» — замечание диджея, и оно
# верное. Лесенка 8/16/32/64 одна на всё означала, что в phonk мы ищем
# фразу там, где её нет, а в трансе обрываем на четверти.
PHRASE_LADDERS: dict[str, tuple[int, ...]] = {
    "bigroom":   (4, 8, 16),
    "dubstep":   (8, 16, 32),
    "neurofunk": (8, 16, 32),
    "jungle":    (8, 16, 32),
    "dnb":       (8, 16, 32),
    "liquid":    (16, 32, 64),
    "house":     (16, 32, 64),
    "techno":    (16, 32, 64),
    "trance":    (16, 32, 64),
    # Семейства, которые определяются по темпу (genre.BPM_FAMILIES).
    # Гэридж и бэйслайн живут короткими квадратами: 8-16 тактов, и
    # 32-тактовое наложение там звучит как затянутая пауза, а не как
    # длинный переход.
    "garage":    (8, 16, 32),
    "bassline":  (8, 16, 32),
    "breaks":    (8, 16, 32),
    "hiphop":    (4, 8, 16),
}


def phrase_ladder(track: dict | None = None) -> tuple[int, ...]:
    """Какими длинами меряются фразы в этом стиле.

    Если жанр не подписан, спрашиваем ТЕМП, а не берём значения по
    умолчанию. Умолчания здесь драм-н-бейсовые, и для трека на 135 BPM
    это чужая сетка — диджей на это и указал: «под эти стили нужны другие
    фразы и другие техники сведения». Темп жанра не называет, но
    семейство сужает, а сетка фраз у семейства одна."""
    if not track:
        return PHRASE_LENGTHS
    g, sub = track_genre(track)
    for key in (sub, g):
        if key and str(key).lower() in PHRASE_LADDERS:
            return PHRASE_LADDERS[str(key).lower()]
    try:
        import genre as _genre

        fam = _genre.genre_from_bpm(track.get("bpm")).get("genre")
        if fam and fam in PHRASE_LADDERS:
            return PHRASE_LADDERS[fam]
    except Exception:                                # noqa: BLE001
        pass
    return PHRASE_LENGTHS


def point_bias(exit_at: float, a_duration: float | None,
               entry_at: float, b_duration: float | None) -> tuple[float, str]:
    """Насколько удачно СТОЯТ точки ухода и входа по хронометражу.

    Вопрос диджея: «секции A — уход, почему берётся первый, а не
    последний, что логично; секции B — вход, почему не первый». Он прав:
    уходить из трека на второй минуте шестиминутного — значит не дать ему
    отыграть, а заходить в новый на четвёртой — выбросить его начало.

    Раньше вес этого не учитывал вовсе: точки сравнивались только по
    типу секции и длине куска. Теперь поздний уход и ранний вход получают
    надбавку, но мягкую — она не должна перебивать сам стык."""
    why = ""
    mult = 1.0
    if a_duration and a_duration > 1.0:
        frac = max(0.0, min(1.0, float(exit_at) / float(a_duration)))
        mult *= 0.8 + 0.4 * frac            # 0.8 в начале трека, 1.2 в конце
        if frac < 0.35:
            why = "уход рано — трек почти не отыграл"
    if b_duration and b_duration > 1.0:
        frac = max(0.0, min(1.0, float(entry_at) / float(b_duration)))
        mult *= 1.2 - 0.4 * frac            # 1.2 у начала, 0.8 у конца
        if frac > 0.65 and not why:
            why = "вход поздно — у входящего останется мало трека"
    return mult, why


def pair_diversity(label: str, recent_labels: list[str]) -> float:
    """Множитель за НЕповторение стыковки.

    Однообразие стыковок и есть та причина, по которой сет звучит
    одинаково, даже когда каждый переход по отдельности выбран верно."""
    if not recent_labels:
        return 1.0
    if label == recent_labels[0]:
        return 0.45
    if label in recent_labels[:2]:
        return 0.65
    if label in recent_labels[:4]:
        return 0.85
    return 1.15
